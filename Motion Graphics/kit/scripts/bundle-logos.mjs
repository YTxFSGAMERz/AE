// Embeds public/logos/* into src/logos.ts so marks render synchronously at render time.
import { readdir, readFile, writeFile } from "node:fs/promises";
const files = await readdir("public/logos");
const entries = [];
for (const f of files.filter((f) => f.endsWith(".paths.json"))) {
  const slug = f.replace(".paths.json", "");
  const meta = JSON.parse(await readFile(`public/logos/${f}`, "utf8"));
  const svg = await readFile(`public/logos/${slug}.svg`, "utf8");
  entries.push(`  ${JSON.stringify(slug)}: { viewBox: ${JSON.stringify(meta.viewBox)}, paths: ${JSON.stringify(meta.paths)}, svg: ${JSON.stringify(svg)} },`);
}
for (const f of files.filter((f) => f.endsWith(".png"))) {
  const slug = f.replace(".png", "");
  if (files.includes(`${slug}.paths.json`)) continue; // svg wins
  entries.push(`  ${JSON.stringify(slug)}: { viewBox: "0 0 1 1", paths: [], svg: "", png: ${JSON.stringify(`logos/${f}`)} },`);
}
await writeFile("src/logos.ts", `// AUTO-GENERATED by scripts/bundle-logos.mjs — brand marks fetched with scripts/fetch-logo.mjs
export type LogoData = { viewBox: string; paths: { d: string; fill?: string }[]; svg: string; png?: string };
export const LOGOS: Record<string, LogoData> = {
${entries.join("\n")}
};
`);
console.log(`bundled ${entries.length} logos → src/logos.ts`);
