// Embeds public/icons/*.svg (Lucide via Iconify) into src/icons.ts
import { readdir, readFile, writeFile } from "node:fs/promises";
const files = (await readdir("public/icons")).filter((f) => f.endsWith(".svg"));
const out = [];
for (const f of files) out.push(`  ${JSON.stringify(f.replace(".svg", ""))}: ${JSON.stringify(await readFile(`public/icons/${f}`, "utf8"))},`);
await writeFile("src/icons.ts", `// AUTO-GENERATED by scripts/bundle-icons.mjs — Lucide icons fetched from api.iconify.design (ISC)\nexport const ICONS: Record<string, string> = {\n${out.join("\n")}\n};\n`);
console.log(`bundled ${out.length} icons`);
